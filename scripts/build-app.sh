#!/usr/bin/env bash
# Builds "build/Hanko Mix.app" (universal, ad-hoc signed).
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

swift build -c release --arch arm64 --arch x86_64 --product HankoMix
BIN_DIR="$(swift build -c release --arch arm64 --arch x86_64 --show-bin-path)"

APP="$ROOT/build/Hanko Mix.app"
rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"
cp App/Info.plist "$APP/Contents/Info.plist"
cp "$BIN_DIR/HankoMix" "$APP/Contents/MacOS/HankoMix"
# SwiftPM resource bundle (autoeq.json); Bundle.module finds it in Contents/Resources.
cp -R "$BIN_DIR/HankoMix_HankoMix.bundle" "$APP/Contents/Resources/"
# App icon (generated by scripts/make-app-icon.swift) and menu bar template images.
cp App/AppIcon.icns "$APP/Contents/Resources/AppIcon.icns"
cp App/MenuBarIcon.png App/MenuBarIcon@2x.png App/MenuBarIcon@3x.png "$APP/Contents/Resources/"

codesign --force --options runtime --entitlements App/HankoMix.entitlements -s - "$APP"
echo "Built $APP"
